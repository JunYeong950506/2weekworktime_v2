const TEN_MILLION_INCOME_TAX = 1_507_400;

function truncateToTenWon(value: number): number {
  return Math.floor(Math.max(0, value) / 10) * 10;
}

function calculateHighIncomeTax(monthlyTaxablePay: number): number {
  if (monthlyTaxablePay <= 14_000_000) {
    return TEN_MILLION_INCOME_TAX
      + (monthlyTaxablePay - 10_000_000) * 0.98 * 0.35
      + 25_000;
  }

  if (monthlyTaxablePay <= 28_000_000) {
    return TEN_MILLION_INCOME_TAX
      + 1_397_000
      + (monthlyTaxablePay - 14_000_000) * 0.98 * 0.38;
  }

  if (monthlyTaxablePay <= 30_000_000) {
    return TEN_MILLION_INCOME_TAX
      + 6_610_600
      + (monthlyTaxablePay - 28_000_000) * 0.98 * 0.4;
  }

  if (monthlyTaxablePay <= 45_000_000) {
    return TEN_MILLION_INCOME_TAX
      + 7_394_600
      + (monthlyTaxablePay - 30_000_000) * 0.4;
  }

  if (monthlyTaxablePay <= 87_000_000) {
    return TEN_MILLION_INCOME_TAX
      + 13_394_600
      + (monthlyTaxablePay - 45_000_000) * 0.42;
  }

  return TEN_MILLION_INCOME_TAX
    + 31_034_600
    + (monthlyTaxablePay - 87_000_000) * 0.45;
}

export function estimateSinglePersonIncomeTax(monthlyTaxablePay: number): number {
  const pay = Math.max(0, Math.round(monthlyTaxablePay));

  if (pay < 1_060_000) {
    return 0;
  }

  if (pay >= 10_000_000) {
    if (pay === 10_000_000) {
      return TEN_MILLION_INCOME_TAX;
    }

    return truncateToTenWon(calculateHighIncomeTax(pay));
  }

  let index: number;
  if (pay < 1_500_000) {
    index = Math.floor((pay - 1_060_000) / 5_000);
  } else if (pay < 3_000_000) {
    index = 88 + Math.floor((pay - 1_500_000) / 10_000);
  } else {
    index = 238 + Math.floor((pay - 3_000_000) / 20_000);
  }

  return SINGLE_PERSON_INCOME_TAX_BY_BRACKET[index] ?? 0;
}

export function estimateSinglePersonWithholding(monthlyTaxablePay: number): number {
  const incomeTax = estimateSinglePersonIncomeTax(monthlyTaxablePay);
  const localIncomeTax = truncateToTenWon(incomeTax * 0.1);

  return incomeTax + localIncomeTax;
}
